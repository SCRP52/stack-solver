export function message(language, key, ...parameters) {
  const value = messages[key]?.[language === 'en' ? 1 : 0] ?? key;
  return typeof value === 'function' ? value(...parameters) : value;
}

export class ConverterError extends Error {
  constructor(code, ...parameters) {
    super(message('vi', code, ...parameters));
    this.code = code;
    this.parameters = parameters;
  }
}
